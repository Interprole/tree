// Generates src/fonts/fonts.generated.ts from the installed font packages.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek', 'greek-ext'];
const FONTSOURCE = [
  { id: 'libertinus', pkg: 'libertinus-serif', family: 'Libertinus Serif', variants: ['400-normal', '400-italic', '700-normal'] },
  { id: 'garamond', pkg: 'eb-garamond', family: 'EB Garamond', variants: ['400-normal', '400-italic', '700-normal'] },
  { id: 'noto-serif', pkg: 'noto-serif', family: 'Noto Serif', variants: ['400-normal', '400-italic', '700-normal'] },
  { id: 'noto-sans', pkg: 'noto-sans', family: 'Noto Sans', variants: ['400-normal', '400-italic', '700-normal'] },
  { id: 'caveat', pkg: 'caveat', family: 'Caveat', variants: ['400-normal', '700-normal'] },
];

const imports = [];
const faces = [];
let k = 0;
const imp = (path) => {
  const name = `f${k++}`;
  imports.push(`import ${name} from '${path}?url';`);
  return name;
};

for (const f of FONTSOURCE) {
  for (const v of f.variants) {
    const [weight, style] = v.split('-');
    const cssFile = `node_modules/@fontsource/${f.pkg}/${weight}${style === 'italic' ? '-italic' : ''}.css`;
    const css = readFileSync(cssFile, 'utf8');
    for (const sub of SUBSETS) {
      const re = new RegExp(`/\\* ${f.pkg}-${sub}-${weight}-${style} \\*/[\\s\\S]*?unicode-range: ([^;]+);`);
      const m = re.exec(css);
      if (!m) continue;
      const base = `@fontsource/${f.pkg}/files/${f.pkg}-${sub}-${weight}-${style}`;
      if (!existsSync(`node_modules/${base}.woff2`)) continue;
      faces.push(`{ id: '${f.id}', family: '${f.family}', weight: ${weight}, style: '${style}', range: '${m[1].trim()}', woff2: ${imp(base + '.woff2')}, sfnt: ${imp(base + '.woff')} }`);
    }
  }
}
// Computer Modern Unicode: complete fonts (Latin, Cyrillic, Greek)
for (const [weight, style, file] of [
  [400, 'normal', 'cmu-serif-500-roman'],
  [400, 'italic', 'cmu-serif-500-italic'],
  [700, 'normal', 'cmu-serif-700-roman'],
]) {
  const base = `computer-modern/fonts/${file}`;
  faces.push(`{ id: 'cmu', family: 'CMU Serif', weight: ${weight}, style: '${style}', range: '', woff2: ${imp(base + '.woff2')}, sfnt: ${imp(base + '.ttf')} }`);
}

// symbol fallback (∅ ′ ⟨⟩ → Greek …) for every family: STIX Two Math, used under a wider unicode-range
{
  const base = '@fontsource/stix-two-math/files/stix-two-math-latin-400-normal';
  faces.push(`{ id: 'symbols', family: 'NanoTrees Symbols', weight: 400, style: 'normal', range: 'U+0370-03FF,U+2000-2BFF', woff2: ${imp(base + '.woff2')}, sfnt: ${imp(base + '.woff')} }`);
}

const out = `// Generated by scripts/gen-fonts.mjs — do not edit.
/* eslint-disable */
${imports.join('\n')}

export interface FontFace {
  id: string;
  family: string;
  weight: number;
  style: 'normal' | 'italic';
  /** CSS unicode-range ('' = everything) */
  range: string;
  woff2: string;
  /** WOFF/TTF file for PDF embedding */
  sfnt: string;
}

export const FACES: FontFace[] = [
  ${faces.join(',\n  ')},
];
`;
writeFileSync('src/fonts/fonts.generated.ts', out);
console.log(`${faces.length} font faces`);
